"""
SUID Forensic Extractor
Used by IT department to extract audit trails for law enforcement.

Usage:
    from suid.forensics.extractor import ForensicExtractor
    report = ForensicExtractor.entity_report("PAT-20260420-KE047-A3X9KM")
"""
from datetime import datetime
from suid.generator import SUID
from suid.validator import validate
from suid.registry.prefixes import PREFIX
from suid.regions.kenya import get_county


class ForensicExtractor:
    """
    Tools for extracting audit information from SUIDs.
    Used in law enforcement requests and internal investigations.
    """

    @staticmethod
    def entity_report(suid: str) -> dict:
        """
        Generate a forensic report for a single entity ID.
        Returns all metadata embedded in the SUID.
        """
        if not validate(suid):
            return {"error": f"Invalid SUID: {suid}"}

        parsed = SUID.parse(suid)

        return {
            "suid":           parsed["suid"],
            "entity_type":    parsed["prefix_name"],
            "created_date":   parsed["date"],
            "origin_county":  parsed["county"],
            "origin_region":  parsed["region"],
            "random_suffix":  parsed["suffix"],
            "forensic_note":  (
                f"This ID identifies a {parsed['prefix_name']} record "
                f"created on {parsed['date']} "
                f"in {parsed['county']} County, Kenya."
            ),
            "db_query": (
                f"SELECT * FROM audit_logs "
                f"WHERE entity_id = '{parsed['suid']}' "
                f"OR related_id = '{parsed['suid']}' "
                f"ORDER BY created_at ASC;"
            ),
        }

    @staticmethod
    def bulk_report(suids: list) -> list:
        """Generate forensic reports for multiple SUIDs."""
        return [ForensicExtractor.entity_report(s) for s in suids]

    @staticmethod
    def filter_by_type(suids: list, prefix: str) -> list:
        """Filter a list of SUIDs by entity type."""
        return [s for s in suids if s.upper().startswith(prefix)]

    @staticmethod
    def filter_by_region(suids: list, region: str) -> list:
        """Filter a list of SUIDs by Kenya county code."""
        return [s for s in suids if f"-{region}-" in s.upper()]

    @staticmethod
    def filter_by_date_range(suids: list, start: str, end: str) -> list:
        """
        Filter SUIDs by creation date range.
        Args:
            start: "YYYY-MM-DD"
            end:   "YYYY-MM-DD"
        """
        result = []
        start_dt = datetime.strptime(start, "%Y-%m-%d").date()
        end_dt   = datetime.strptime(end,   "%Y-%m-%d").date()

        for suid in suids:
            parsed = SUID.parse(suid)
            if not parsed.get("valid"):
                continue
            created = datetime.strptime(parsed["date"], "%Y-%m-%d").date()
            if start_dt <= created <= end_dt:
                result.append(suid)
        return result

    @staticmethod
    def law_enforcement_summary(suids: list, case_number: str = "") -> dict:
        """
        Generate a structured law enforcement summary report.
        Format suitable for official submission.
        """
        reports   = ForensicExtractor.bulk_report(suids)
        valid     = [r for r in reports if "error" not in r]
        by_type   = {}
        by_region = {}

        for r in valid:
            t = r["entity_type"]
            c = r["origin_county"]
            by_type[t]   = by_type.get(t, 0) + 1
            by_region[c] = by_region.get(c, 0) + 1

        return {
            "case_number":      case_number,
            "generated_at":     datetime.utcnow().isoformat() + "Z",
            "system":           "Sorabbyngo Identity Core",
            "total_ids":        len(suids),
            "valid_ids":        len(valid),
            "invalid_ids":      len(suids) - len(valid),
            "entities_by_type": by_type,
            "entities_by_region": by_region,
            "records":          valid,
            "note": (
                "This report was generated by the Sorabbyngo IT department "
                "in response to a lawful request. All IDs are traceable to "
                "specific entity types, creation dates, and Kenyan counties."
            ),
        }
